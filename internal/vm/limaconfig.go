// Fixed locations and names inside the VM. The provisioning scripts below
// spell these paths out literally; limaconfig_test.go checks they agree.
const (
	// PublishedPortFirst..PublishedPortLast is the only range of guest
	// ports that Lima forwards to the same ports on the host loopback.
	// A container published there (`docker run -p 30000:5432 …`) is
	// reachable from host tools; every other guest listener stays inside
	// the VM.
	PublishedPortFirst = 30000
	PublishedPortLast  = 30099
	// ModeFile holds "online" or "offline"; absent means offline once the
	// VM is provisioned. Root-owned, read by the boot script.
	ModeFile = "/etc/omac-vm/mode"
	// PackagesFile lists the extra apt packages, space-separated.
	PackagesFile = "/etc/omac-vm/packages"
	// ProvisionedMarker exists once the system script finished installing.
	ProvisionedMarker = "/var/lib/omac-vm/provisioned"
	// RulesetFile is where the boot script writes Ruleset().
	RulesetFile = "/etc/omac-vmguard.nft"
	// GuardTable is the nftables table defined by Ruleset().
	GuardTable = "omac-vmguard"
)

// heredocEnd terminates the heredoc that writes the ruleset in the boot
// script; a ruleset line equal to it would end the heredoc early.
const heredocEnd = "OMACVMGUARD"

// LimaInputs is everything RenderLimaConfig needs to describe the VM.
type LimaInputs struct {
	Resources   Resources
	SSHPort     int
	AgentUser   string   // Lima user name, see AgentUserName
	AdminPubKey string   // content of admin_key.pub (one line)
	AgentPubKey string   // content of agent_key.pub
	Packages    []string // apt packages: vm.yaml packages, then the JDK packages
	Ruleset     string
}

var (
	agentUserPattern = regexp.MustCompile(`^[a-z_][a-z0-9_-]{0,31}$`)
	packagePattern   = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9.+-]*$`)
	sizePattern      = regexp.MustCompile(`^[0-9]+(\.[0-9]+)?[A-Za-z]*$`)
)

// RenderLimaConfig returns the Lima YAML for the omac VM. Values that end up
// in shell lines are validated so they cannot break out of their quoting.
func RenderLimaConfig(in LimaInputs) (string, error) {
	if err := validateLimaInputs(in); err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# omac VM (generated by omac vm up; do not edit, run `omac vm reset` instead)\n")
	b.WriteString("base:\n  - template:_images/ubuntu-24.04\n")
	b.WriteString("cpus: " + strconv.Itoa(in.Resources.CPUs) + "\n")
	b.WriteString("memory: " + in.Resources.Memory + "\n")
	b.WriteString("disk: " + in.Resources.Disk + "\n")
	b.WriteString("user:\n  name: " + in.AgentUser + "\n")
	b.WriteString("containerd: {system: false, user: false}\n")
	b.WriteString("mounts: []\n")
	b.WriteString("ssh:\n  localPort: " + strconv.Itoa(in.SSHPort) + "\n")
	b.WriteString("portForwards:\n")
	published := "[" + strconv.Itoa(PublishedPortFirst) + ", " + strconv.Itoa(PublishedPortLast) + "]"
	b.WriteString("  - guestIP: 127.0.0.1\n")
	b.WriteString("    guestPortRange: " + published + "\n")
	b.WriteString("    hostIP: 127.0.0.1\n")
	b.WriteString("    hostPortRange: " + published + "\n")
	b.WriteString("    proto: tcp\n")
	// Without these, Lima forwards every other guest listener to the same
	// port on the host's loopback, so a VM process could claim a host port
	// that a host tool later connects to.
	for _, ip := range []string{"127.0.0.1", "0.0.0.0"} {
		b.WriteString("  - guestIP: " + ip + "\n")
		b.WriteString("    guestPortRange: [1, 65535]\n")
		b.WriteString("    proto: any\n")
		b.WriteString("    ignore: true\n")
	}
	b.WriteString("provision:\n")

	b.WriteString("  - mode: boot\n    script: |\n")
	writeScript(&b, bootScriptHead)
	writeScript(&b, strings.TrimSuffix(in.Ruleset, "\n"))
	writeScript(&b, bootScriptTail)

	b.WriteString("  - mode: system\n    script: |\n")
	writeScript(&b, strings.NewReplacer(
		"<ADMIN_PUB_KEY>", in.AdminPubKey,
		"<AGENT_USER>", in.AgentUser,
		"<PACKAGES>", strings.Join(in.Packages, " "),
	).Replace(systemScript))

	b.WriteString("  - mode: user\n    script: |\n")
	writeScript(&b, strings.ReplaceAll(userScript, "<AGENT_PUB_KEY>", in.AgentPubKey))
	return b.String(), nil
}

// writeScript appends script lines indented as a YAML literal block under
// "script: |". Empty lines stay empty so no trailing whitespace appears.
func writeScript(b *strings.Builder, script string) {
	for _, line := range strings.Split(script, "\n") {
		if line != "" {
			b.WriteString("      ")
			b.WriteString(line)
		}
		b.WriteString("\n")
	}
}

func validateLimaInputs(in LimaInputs) error {
	var errs []error
	if in.Resources.CPUs <= 0 {
		errs = append(errs, fmt.Errorf("cpus must be positive, got %d", in.Resources.CPUs))
	}
	if !sizePattern.MatchString(in.Resources.Memory) {
		errs = append(errs, fmt.Errorf("memory %q is not a size like 16GiB", in.Resources.Memory))
	}
	if !sizePattern.MatchString(in.Resources.Disk) {
		errs = append(errs, fmt.Errorf("disk %q is not a size like 60GiB", in.Resources.Disk))
	}
	if in.SSHPort <= 0 || in.SSHPort > 65535 {
		errs = append(errs, fmt.Errorf("ssh port %d out of range", in.SSHPort))
	}
	if !agentUserPattern.MatchString(in.AgentUser) {
		errs = append(errs, fmt.Errorf("agent user %q is not a valid user name", in.AgentUser))
	}
	for _, k := range []struct{ name, key string }{
		{"admin pub key", in.AdminPubKey},
		{"agent pub key", in.AgentPubKey},
	} {
		if k.key == "" || strings.ContainsAny(k.key, "'\n\r") {
			errs = append(errs, fmt.Errorf("%s must be one non-empty line without single quotes", k.name))
		}
	}
	for _, p := range in.Packages {
		if !packagePattern.MatchString(p) {
			errs = append(errs, fmt.Errorf("package name %q has characters outside [A-Za-z0-9.+-]", p))
		}
	}
	if strings.TrimSpace(in.Ruleset) == "" {
		errs = append(errs, errors.New("ruleset is empty"))
	}
	for _, line := range strings.Split(in.Ruleset, "\n") {
		if line == heredocEnd {
			errs = append(errs, fmt.Errorf("ruleset must not contain the line %q", heredocEnd))
		}
	}
	return errors.Join(errs...)
}

// AgentUserName derives the in-VM user name from the host user: lowercase,
// characters outside [a-z0-9_-] become "-", a name not starting with a
// letter or "_" gets a "_" prefix, and an empty name or "root" becomes "omac".
func AgentUserName(hostUser string) string {
	name := strings.Map(func(r rune) rune {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_' || r == '-' {
			return r
		}
		return '-'
	}, strings.ToLower(hostUser))
	if name == "" || name == "root" {
		return "omac"
	}
	if c := name[0]; !(c >= 'a' && c <= 'z') && c != '_' {
		name = "_" + name
	}
	if len(name) > 32 {
		name = name[:32]
	}
	return name
}

// The boot script runs as root on every start. Before the first
// provisioning finished, the VM stays online so apt can download; after
// that ModeFile decides, defaulting to offline with the firewall loaded.
const bootScriptHead = `#!/bin/bash
set -eu
mkdir -p /etc/omac-vm /var/lib/omac-vm
ln -sf /run/systemd/resolve/resolv.conf /etc/resolv.conf
cat > /etc/omac-vmguard.nft <<'OMACVMGUARD'`

const bootScriptTail = `OMACVMGUARD
mode=offline
[ -f /var/lib/omac-vm/provisioned ] || mode=online
[ -f /etc/omac-vm/mode ] && mode="$(cat /etc/omac-vm/mode)"
if [ "$mode" = online ]; then
  echo "omac-vm: online mode, firewall not loaded"
  exit 0
fi
nft -f /etc/omac-vmguard.nft
nft list table inet omac-vmguard >/dev/null`

// systemScript runs as root on every boot. Moving cloud-init's sudoers
// drop-in removes the agent user's sudo; root is reachable only over SSH
// with admin_key. The offline firewall depends on this: an agent with root
// could unload it.
const systemScript = `#!/bin/bash
set -eu
hn="$(hostname)"
grep -q "127.0.1.1 $hn" /etc/hosts || echo "127.0.1.1 $hn" >> /etc/hosts
# Lima sets a new cloud-init instance-id per boot, which would regenerate the SSH host keys omac pins.
mkdir -p /etc/cloud/cloud.cfg.d
printf 'ssh_deletekeys: false\n' > /etc/cloud/cloud.cfg.d/99-omac-keep-hostkeys.cfg
if [ -f /etc/sudoers.d/90-cloud-init-users ]; then mv /etc/sudoers.d/90-cloud-init-users /root/90-cloud-init-users.disabled; fi
install -d -m 0700 /root/.ssh
printf '%s\n' '<ADMIN_PUB_KEY>' > /root/.ssh/authorized_keys
chmod 0600 /root/.ssh/authorized_keys
loginctl enable-linger <AGENT_USER> || true
mkdir -p /etc/omac-vm /var/lib/omac-vm
[ -f /etc/omac-vm/packages ] || printf '%s\n' '<PACKAGES>' > /etc/omac-vm/packages
[ -f /var/lib/omac-vm/provisioned ] && exit 0
export DEBIAN_FRONTEND=noninteractive
dpkg --configure -a || true
apt-get update
apt-get install -y ca-certificates curl uidmap dbus-user-session nftables slirp4netns wget apt-transport-https gpg
install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
echo "deb [signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo $VERSION_CODENAME) stable" > /etc/apt/sources.list.d/docker.list
wget -qO- https://packages.adoptium.net/artifactory/api/gpg/key/public | gpg --dearmor --yes -o /etc/apt/keyrings/adoptium.gpg
echo "deb [signed-by=/etc/apt/keyrings/adoptium.gpg] https://packages.adoptium.net/artifactory/deb $(. /etc/os-release && echo $VERSION_CODENAME) main" > /etc/apt/sources.list.d/adoptium.list
apt-get update
apt-get install -y docker-ce docker-ce-cli containerd.io docker-ce-rootless-extras
extra="$(cat /etc/omac-vm/packages)"
if [ -n "$extra" ]; then apt-get install -y $extra; fi
systemctl disable --now docker.service docker.socket containerd.service || true
systemctl mask docker.service docker.socket containerd.service || true
date -u +%FT%TZ > /var/lib/omac-vm/provisioned`

// userScript runs as the agent user on every boot, so a failed Docker start
// is retried on the next boot. The user D-Bus starts first because the
// system script installs dbus-user-session after the user's systemd
// manager came up. dockerd listens only on its Unix socket; omac reaches
// it over ssh.
const userScript = `#!/bin/bash
set -eu
mkdir -p ~/.ssh && chmod 0700 ~/.ssh
grep -qF '<AGENT_PUB_KEY>' ~/.ssh/authorized_keys 2>/dev/null || printf '%s\n' '<AGENT_PUB_KEY>' >> ~/.ssh/authorized_keys
chmod 0600 ~/.ssh/authorized_keys
command -v dockerd-rootless-setuptool.sh >/dev/null || exit 0
systemctl --user start dbus || true
[ -f ~/.config/systemd/user/docker.service ] || dockerd-rootless-setuptool.sh install
systemctl --user enable --now docker
for f in ~/.bashrc ~/.profile; do grep -q '^export DOCKER_HOST=' "$f" 2>/dev/null || printf 'export DOCKER_HOST=unix:///run/user/%s/docker.sock\n' "$(id -u)" >> "$f"; done
printf 'docker.host=unix:///run/user/%s/docker.sock\n' "$(id -u)" > ~/.testcontainers.properties`
